export type SiteContentKey = keyof typeof SITE_CONTENT_DEFAULTS;
export type SiteContent = Record<SiteContentKey, string>;

export type SiteContentField = {
  key: SiteContentKey;
  label: string;
  multiline?: boolean;
};

export type SiteContentImageField = {
  key: SiteContentKey;
  label: string;
  altKey: SiteContentKey;
  slot: "hero" | "portfolio";
};

export type SiteContentSection = {
  id: string;
  title: string;
  fields: readonly SiteContentField[];
  images?: readonly SiteContentImageField[];
};

const field = (
  key: SiteContentKey,
  label: string,
  multiline = false,
): SiteContentField => ({ key, label, ...(multiline ? { multiline: true } : {}) });

const image = (
  key: SiteContentKey,
  label: string,
  altKey: SiteContentKey,
  slot: SiteContentImageField["slot"],
): SiteContentImageField => ({ key, label, altKey, slot });

